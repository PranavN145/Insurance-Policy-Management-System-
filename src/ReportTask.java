/**
 * ReportTask.java
 *
 * Implements Task 3 (Member 3): Multithreading
 * Extends the Java Thread class to generate a comprehensive system summary
 * audit report asynchronously in the background.
 *
 * Demonstrates:
 * - Extending Thread class and overriding run()
 * - Passing data snapshot through constructor
 * - Thread lifecycle (New -> Runnable -> Running -> Terminated)
 * - Using start() instead of directly invoking run()
 * - Handling InterruptedException during simulated processing
 */
public class ReportTask extends Thread {

    private int customerCount;
    private int planCount;
    private int policyCount;
    private int activePolicyCount;
    private int cancelledPolicyCount;
    private int paymentCount;
    private double totalRevenue;
    private int claimCount;
    private int pendingClaims;
    private int approvedClaims;
    private int rejectedClaims;
    private double approvedPayout;

    /**
     * Parameterized constructor receiving a snapshot of system metrics.
     */
    public ReportTask(int customerCount, int planCount, int policyCount,
                      int activePolicyCount, int cancelledPolicyCount,
                      int paymentCount, double totalRevenue,
                      int claimCount, int pendingClaims,
                      int approvedClaims, int rejectedClaims,
                      double approvedPayout) {
        this.customerCount = customerCount;
        this.planCount = planCount;
        this.policyCount = policyCount;
        this.activePolicyCount = activePolicyCount;
        this.cancelledPolicyCount = cancelledPolicyCount;
        this.paymentCount = paymentCount;
        this.totalRevenue = totalRevenue;
        this.claimCount = claimCount;
        this.pendingClaims = pendingClaims;
        this.approvedClaims = approvedClaims;
        this.rejectedClaims = rejectedClaims;
        this.approvedPayout = approvedPayout;
    }

    /**
     * Thread execution entry point.
     * Simulates background processing with Thread.sleep and prints report.
     */
    @Override
    public void run() {
        System.out.println("\n[ReportTask Thread: " + Thread.currentThread().getName() 
                + "] Starting asynchronous audit report generation...");

        try {
            // Simulate brief background computation / compilation delay
            Thread.sleep(800);
        } catch (InterruptedException e) {
            System.out.println("[ReportTask Thread] Report generation was interrupted: " + e.getMessage());
            return;
        }

        System.out.println("\n=============================================================");
        System.out.println("     *** AUDIT & PERFORMANCE SUMMARY REPORT (BACKGROUND) *** ");
        System.out.println("=============================================================");
        System.out.println(" Generated by Thread : " + Thread.currentThread().getName());
        System.out.println(" Status              : COMPLETED SUCCESSFULLY");
        System.out.println("-------------------------------------------------------------");
        System.out.println(" Customer Metrics    : Total Registered = " + customerCount);
        System.out.println(" Plan Portfolio      : Active Insurance Plans = " + planCount);
        System.out.println(" Policy Lifecycle    : Total Enrolled = " + policyCount);
        System.out.println("                       - Active Policies     = " + activePolicyCount);
        System.out.println("                       - Cancelled Policies  = " + cancelledPolicyCount);
        System.out.println(" Financial Metrics   : Processed Payments  = " + paymentCount);
        System.out.println("                       - Total Revenue (Rs)  = " + String.format("%.2f", totalRevenue));
        System.out.println(" Claim Liabilities   : Total Claims Filed  = " + claimCount);
        System.out.println("                       - Pending Claims      = " + pendingClaims);
        System.out.println("                       - Approved Claims     = " + approvedClaims);
        System.out.println("                       - Rejected Claims     = " + rejectedClaims);
        System.out.println("                       - Total Payout (Rs)   = " + String.format("%.2f", approvedPayout));
        System.out.println("=============================================================");
        System.out.println("[ReportTask Thread] Report task completed successfully.\n");
    }
}
